/**
 * Finds an icon by name, returning null when there is none — the caller
 * decides between the fallback and nothing at all.
 */
export function resolveIcon(name: string | null | undefined): Component | null {
  if (!name) return null
  return REGISTRY[name] ?? REGISTRY[normalizeIconName(name)] ?? null
}

/**
 * The registry's spelling of a name written another way: `ShoppingCart`,
 * `shopping_cart`, ` Shopping-Cart ` and `lucide-shopping-cart` all mean
 * `shopping-cart`.
 */
export function normalizeIconName(name: string): string {
  return name
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Za-z])(\d)/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .toLowerCase()
    .replace(/^lucide-/, '')
}

/** Every registered name, for docs and tests. */
export function iconNames(): string[] {
  return Object.keys(REGISTRY).sort()
}

/** Registers an extra icon, from a host project. */
export function registerIcon(name: string, component: Component): void {
  REGISTRY[name] = component
}
